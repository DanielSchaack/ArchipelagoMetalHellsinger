def get_location_names_with_ids(location_names: list[str]) -> dict[str, int | None]:
    return {location_name: location_name_to_id[location_name] for location_name in location_names}

def create_all_locations(world: "MetalHellsingerWorld"):
    all_regions_to_add: list[str] = []
    all_locationtypes_to_add: list[str] = []
    if world.options.win_condition == WinCondition.option_hells_completion or world.options.win_condition == WinCondition.option_sheol_completion:
        all_regions_to_add += [
            "Global",
            "Tutorial",
            "Voke Arena1",
            "Voke Arena2",
            "Voke Arena3",
            "Voke Arena4",
            "Voke Boss",
            "Stygia Arena1",
            "Stygia Arena2",
            "Stygia Arena3",
            "Stygia Arena4",
            "Stygia Boss",
            "Yhelm Arena1",
            "Yhelm Arena2",
            "Yhelm Arena3",
            "Yhelm Arena4",
            "Yhelm Boss",
            "Incaustis Arena1",
            "Incaustis Arena2",
            "Incaustis Arena3",
            "Incaustis Arena4",
            "Incaustis Boss",
            "Gehenna Arena1",
            "Gehenna Arena2",
            "Gehenna Arena3",
            "Gehenna Arena4",
            "Gehenna Boss",
            "Nihil Arena1",
            "Nihil Arena2",
            "Nihil Arena3",
            "Nihil Arena4",
            "Nihil Boss",
            "Acheron Arena1",
            "Acheron Arena2",
            "Acheron Arena3",
            "Acheron Arena4",
            "Acheron Boss",
            "Sheol Arena1",
            "Sheol Arena2",
            "Sheol Arena3",
            "Sheol Arena4",
            "Sheol Boss",
        ]
        all_locationtypes_to_add += [
            "AnguishGate",
            "WeaponPickup",
            "NextMultiplier",
            "MaxMultiplier",
            "LevelCompletion",
            "Codex",
            "Bestiary",
        ]

        if world.options.include_section_clears_with_weapons_checks:
            all_locationtypes_to_add.append("SectionClearWeapon")
            all_regions_to_add.append("Weapon Basegame")
            if world.options.include_dream_of_the_beast_weapon:
                all_regions_to_add.append("Weapon DreamOfTheBeast")
            if world.options.include_purgatory_weapon:
                all_regions_to_add.append("Weapon Purgatory")
            if world.options.include_additional_weapon_variants:
                all_regions_to_add.append("Weapon Extra")

        if world.options.include_section_clears_with_outfits_checks:
            all_locationtypes_to_add.append("SectionClearOutfit")
            all_regions_to_add.append("Outfit Basegame")
            if world.options.include_dream_of_the_beast_outfits:
                all_regions_to_add.append("Outfit DreamOfTheBeast")
            if world.options.include_purgatory_outfits:
                all_regions_to_add.append("Outfit Purgatory")

        if world.options.include_section_clears_with_songs_checks:
            all_locationtypes_to_add.append("SectionClearMainSong")
            all_locationtypes_to_add.append("SectionClearBossSong")
            all_regions_to_add.append("Song Basegame")
            if world.options.include_dream_of_the_beast_songs:
                all_regions_to_add.append("Song DreamOfTheBeast")
            if world.options.include_purgatory_songs:
                all_regions_to_add.append("Song Purgatory")
            if world.options.include_dusk_soundtrack_songs:
                all_regions_to_add.append("Song DuskSoundtrack")
            if world.options.include_essential_hits_soundtrack_songs:
                all_regions_to_add.append("Song EssentialHits")

        if world.options.randomized_torments_enabled:
            all_locationtypes_to_add.append("TormentCompletion")
            torment_region_names = [
                f"{challenge} Torment{t}"
                for challenge in [
                    "KillingWithRhythm",
                    "Giantslayer",
                    "UltimateMastery",
                    "SlaughterMastery",
                    "RelicThief",
                    "WeaponTrickery",
                    "DeathsEdge",
                ]
                for t in range(1, 4)
            ]
            all_regions_to_add.extend(torment_region_names)

            if world.options.torment_medaillons_enabled:
                all_locationtypes_to_add.append("TormentBronze")
                all_locationtypes_to_add.append("TormentSilver")
                all_locationtypes_to_add.append("TormentGold")

        if world.options.require_coat_of_arms_for_sheol or world.options.include_coat_of_arms_checks or world.options.include_randomized_weapon_skins_checks:
            all_locationtypes_to_add.append("CoatOfArms")

        if world.options.randomized_boons_enabled:
            all_locationtypes_to_add.append("Boon")

        if world.options.include_randomized_weapon_skins_checks:
            all_locationtypes_to_add.append("WeaponSkin")

        if world.options.include_secret_multiplier_checks:
            all_locationtypes_to_add.append("SecretMultiplier")

        if world.options.include_miscellaneous_checks:
            all_locationtypes_to_add.append("FirstMiscellaneous")
            if world.options.include_dream_of_the_beast_weapon:
                location_id = get_location_names_with_ids(["Activate the Red Right Hands Ultimate for the first time"])
                world.get_region("Global").add_locations(location_id, MetalHellsingerLocation)
            if world.options.include_purgatory_weapon:
                location_id = get_location_names_with_ids(["Activate Telos' Ultimate for the first time"])
                world.get_region("Global").add_locations(location_id, MetalHellsingerLocation)
            if(world.options.randomized_jump_enabled):
                location_id = get_location_names_with_ids(["First Miscellaneous - Infinite Jump"])
                world.get_region("Global").add_locations(location_id, MetalHellsingerLocation)

        if world.options.destructible_locations_enabled and not world.options.singular_destructible_locations_enabled:
            all_locationtypes_to_add.append("ArenaDestructibleCompletion")
        elif world.options.destructible_locations_enabled and world.options.singular_destructible_locations_enabled:
            all_locationtypes_to_add.append("ArenaAmmostashCompletion")
            all_locationtypes_to_add.append("ArenaHealthCrystalCompletion")
            all_locationtypes_to_add.append("ArenaChaosCrystalCompletion")

        if world.options.hells_destructible_locations_enabled:
            all_locationtypes_to_add.append("LevelAmmostashCompletion")
            all_locationtypes_to_add.append("LevelHealthCrystalCompletion")
            all_locationtypes_to_add.append("LevelChaosCrystalCompletion")

    for region_name, locations in location_region_mapping.items():
        if region_name not in all_regions_to_add:
            continue

        valid_location_names: list[str] = []

        for loc_name, loc_info in locations.items():
            if loc_info.ltype in all_locationtypes_to_add:
                valid_location_names.append(loc_name)

        location_ids = get_location_names_with_ids(valid_location_names)
        world.get_region(region_name).add_locations(location_ids, MetalHellsingerLocation)

def create_events(world: "MetalHellsingerWorld") -> None:
    if world.options.win_condition == WinCondition.option_hells_completion or world.options.win_condition == WinCondition.option_sheol_completion:
        voke_boss = world.get_region("Voke Boss")
        voke_boss.add_event("Anger Aspect: Voke defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        stygia_boss = world.get_region("Stygia Boss")
        stygia_boss.add_event("Charged Aspect: Stygia defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        yhelm_boss = world.get_region("Yhelm Boss")
        yhelm_boss.add_event("Fortress Aspect: Yhelm defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        incaustis_boss = world.get_region("Incaustis Boss")
        incaustis_boss.add_event("Infernal Fury Aspect: Incaustis defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        gehenna_boss = world.get_region("Gehenna Boss")
        gehenna_boss.add_event("Hellstorm Aspect: Gehenna defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        nihil_boss = world.get_region("Nihil Boss")
        nihil_boss.add_event("Doppelganger Aspect: Nihil defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        acheron_boss = world.get_region("Acheron Boss")
        acheron_boss.add_event("Wheel Aspect: Acheron defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        sheol_boss = world.get_region("Sheol Boss")
        sheol_boss.add_event("Red Judge - Worldbreaker: Sheol defeated", "Aspect Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)
        sheol_boss.add_event("Red Judge - Worldbreaker: Sheol slain", "Red Judge Slain", location_type=MetalHellsingerLocation, item_type=MetalHellsingerItem)


